namespace Catharsis.DataAnnotations;

///<summary>
///Specifies the sort direction for <see cref="SortedAttribute"/> validation.
///</summary>
public enum SortDirection
{
    ///<summary>
    ///Elements must be in ascending order.
    ///</summary>
    Ascending,

    ///<summary>
    ///Elements must be in descending order.
    ///</summary>
    Descending
}
